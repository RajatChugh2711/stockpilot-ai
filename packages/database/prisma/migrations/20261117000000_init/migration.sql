  FOREIGN KEY ("exchange_id") REFERENCES "exchanges"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "provider_instruments" ADD CONSTRAINT "provider_instruments_provider_id_fkey"
  FOREIGN KEY ("provider_id") REFERENCES "data_providers"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "provider_instruments" ADD CONSTRAINT "provider_instruments_instrument_id_fkey"
  FOREIGN KEY ("instrument_id") REFERENCES "instruments"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "market_prices" ADD CONSTRAINT "market_prices_instrument_id_fkey"
  FOREIGN KEY ("instrument_id") REFERENCES "instruments"("id") ON DELETE CASCADE ON UPDATE CASCADE;
