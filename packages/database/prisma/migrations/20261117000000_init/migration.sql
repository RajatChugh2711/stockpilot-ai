CREATE TYPE "UserRole" AS ENUM ('USER', 'ADMIN', 'SUPPORT');
CREATE TYPE "InstrumentType" AS ENUM ('EQUITY', 'ETF', 'INDEX');
CREATE TYPE "PriceBasis" AS ENUM ('RAW', 'SPLIT_ADJUSTED', 'TOTAL_RETURN');
CREATE TYPE "IngestionStatus" AS ENUM ('QUEUED', 'RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED');

CREATE TABLE "users" (
  "id" UUID NOT NULL,
  "email" VARCHAR(320) NOT NULL,
  "password_hash" VARCHAR(255) NOT NULL,
  "display_name" VARCHAR(120),
  "role" "UserRole" NOT NULL DEFAULT 'USER',
  "active" BOOLEAN NOT NULL DEFAULT true,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL,
  CONSTRAINT "users_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "users_email_key" ON "users"("email");

CREATE TABLE "user_sessions" (
  "id" UUID NOT NULL,
  "user_id" UUID NOT NULL,
  "refresh_token_hash" VARCHAR(255) NOT NULL,
  "expires_at" TIMESTAMPTZ(6) NOT NULL,
  "revoked_at" TIMESTAMPTZ(6),
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "user_sessions_pkey" PRIMARY KEY ("id")
);
CREATE INDEX "user_sessions_user_id_expires_at_idx" ON "user_sessions"("user_id", "expires_at");

CREATE TABLE "companies" (
  "id" UUID NOT NULL,
  "name" VARCHAR(255) NOT NULL,
  "isin" VARCHAR(12),
  "industry" VARCHAR(150),
  "description" TEXT,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL,
  CONSTRAINT "companies_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "companies_isin_key" ON "companies"("isin");
CREATE INDEX "companies_name_idx" ON "companies"("name");

CREATE TABLE "exchanges" (
  "id" UUID NOT NULL,
  "code" VARCHAR(10) NOT NULL,
  "name" VARCHAR(100) NOT NULL,
  "country_code" CHAR(2) NOT NULL DEFAULT 'IN',
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "exchanges_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "exchanges_code_key" ON "exchanges"("code");

CREATE TABLE "instruments" (
  "id" UUID NOT NULL,
  "company_id" UUID NOT NULL,
  "exchange_id" UUID NOT NULL,
  "symbol" VARCHAR(50) NOT NULL,
  "security_code" VARCHAR(30),
  "instrument_type" "InstrumentType" NOT NULL DEFAULT 'EQUITY',
  "currency" CHAR(3) NOT NULL DEFAULT 'INR',
  "active" BOOLEAN NOT NULL DEFAULT true,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMPTZ(6) NOT NULL,
  CONSTRAINT "instruments_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "instruments_exchange_id_symbol_key" ON "instruments"("exchange_id", "symbol");
CREATE INDEX "instruments_company_id_idx" ON "instruments"("company_id");

CREATE TABLE "data_providers" (
  "id" UUID NOT NULL,
  "code" VARCHAR(50) NOT NULL,
  "name" VARCHAR(150) NOT NULL,
  "enabled" BOOLEAN NOT NULL DEFAULT false,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "data_providers_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "data_providers_code_key" ON "data_providers"("code");

CREATE TABLE "provider_instruments" (
  "id" UUID NOT NULL,
  "provider_id" UUID NOT NULL,
  "instrument_id" UUID NOT NULL,
  "external_instrument_id" VARCHAR(120) NOT NULL,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "provider_instruments_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "provider_instruments_provider_id_external_instrument_id_key" ON "provider_instruments"("provider_id", "external_instrument_id");
CREATE UNIQUE INDEX "provider_instruments_provider_id_instrument_id_key" ON "provider_instruments"("provider_id", "instrument_id");

CREATE TABLE "market_prices" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "instrument_id" UUID NOT NULL,
  "provider_id" UUID,
  "trading_date" DATE NOT NULL,
  "interval" VARCHAR(10) NOT NULL DEFAULT '1d',
  "price_basis" "PriceBasis" NOT NULL DEFAULT 'RAW',
  "open" DECIMAL(18,4),
  "high" DECIMAL(18,4),
  "low" DECIMAL(18,4),
  "close" DECIMAL(18,4) NOT NULL,
  "volume" BIGINT,
  "source_as_of" TIMESTAMPTZ(6),
  "ingested_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "market_prices_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "market_prices_instrument_id_trading_date_interval_price_basis_key" ON "market_prices"("instrument_id", "trading_date", "interval", "price_basis");
CREATE INDEX "market_prices_instrument_id_trading_date_idx" ON "market_prices"("instrument_id", "trading_date" DESC);
CREATE INDEX "market_prices_provider_id_ingested_at_idx" ON "market_prices"("provider_id", "ingested_at");

CREATE TABLE "ingestion_jobs" (
  "id" UUID NOT NULL,
  "provider_id" UUID NOT NULL,
  "data_type" VARCHAR(50) NOT NULL,
  "status" "IngestionStatus" NOT NULL DEFAULT 'QUEUED',
  "started_at" TIMESTAMPTZ(6),
  "finished_at" TIMESTAMPTZ(6),
  "records_read" INTEGER NOT NULL DEFAULT 0,
  "records_stored" INTEGER NOT NULL DEFAULT 0,
  "error_message" TEXT,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "ingestion_jobs_pkey" PRIMARY KEY ("id")
);
CREATE INDEX "ingestion_jobs_provider_id_created_at_idx" ON "ingestion_jobs"("provider_id", "created_at" DESC);

